CREATE TABLE users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) NOT NULL UNIQUE,
    email VARCHAR2(255) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    full_name VARCHAR2(100),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    is_active NUMBER(1) DEFAULT 1 CHECK (is_active IN (0, 1)) -- 1 for True, 0 for False
);

CREATE TABLE user_sessions (
    session_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    token VARCHAR2(500) NOT NULL UNIQUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_user_sessions_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id)
        ON DELETE CASCADE
);

CREATE TABLE games (
    game_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(255) NOT NULL UNIQUE,
    description CLOB, -- Large text for game details
    image_url VARCHAR2(500), -- Link to the cover art
    platform VARCHAR2(50),
    price NUMBER(6,2) NOT NULL,
    release_date DATE DEFAULT SYSDATE
);

CREATE TABLE user_library (
    library_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    game_id NUMBER NOT NULL,
    platform VARCHAR2(50),
    CONSTRAINT fk_user
        FOREIGN KEY (user_id) REFERENCES users(user_id),
    CONSTRAINT fk_game
        FOREIGN KEY (game_id) REFERENCES games(game_id)
);